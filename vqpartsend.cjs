/* ══════════════════════════════════════════════════════════════════════
   試験の 頼みが「**その 頼みが 作る 大問だけ**」を 送るか 確かめる。

   なぜ 要るか（2026-09-05）:
     1 回の 頼みは requestsOf が 大問ごとに 刻むので、中身は いつも
     1 つの 大問ぶん。なのに 全 12 大問を 送って いたので、
     サーバが 12 に 割ろうと して 呼び出しの 予算が そこで 削られていた。

   ★ ここを 間違えると **別の 大問の 問題を 作る**（黙って 中身が 入れ替わる）。
     plan の 大問番号は「問題が 0 の 大問を 落としてから」振り直されるので、
     人が 並べた st.範囲 とは ずれる。だから 題で 突き合わせる。
   ══════════════════════════════════════════════════════════════════════ */
const fs = require("fs");
const src = fs.readFileSync(__dirname + "/js-src/vq-make.js", "utf8");

/* 関数だけを 取り出して 動かす（画面ぜんぶは 起こさない）。 */
const 頭 = src.indexOf("  function 出題範囲(手がかり) {");
if (頭 < 0) { console.error("✗ 出題範囲() が 見つかりません"); process.exit(1); }
let 深 = 0, 尾 = -1;
for (let i = src.indexOf("{", 頭); i < src.length; i++) {
  if (src[i] === "{") 深++;
  else if (src[i] === "}") { 深--; if (深 === 0) { 尾 = i + 1; break; } }
}
const 本体 = src.slice(頭, 尾);

let 合 = 0, 否 = 0;
function 見る(名, 実, 期) {
  const a = JSON.stringify(実), b = JSON.stringify(期);
  if (a === b) { console.log("  ✓ " + 名); 合++; }
  else { console.log("  ✗ " + 名 + "\n      出た: " + a + "\n      ほしい: " + b); 否++; }
}
function 作る(範囲) {
  const st = { 範囲: 範囲 };
  return new Function("st", 本体 + "; return 出題範囲;")(st);
}
const 題名 = (x) => (x || []).map((p) => p.title);

console.log("\n══ その頼みが作る大問だけを送る ══\n");

const 三 = [
  { title: "第1問 古代", where: "p.10-20", count: 4 },
  { title: "第2問 中世", where: "p.21-40", count: 4 },
  { title: "第3問 近世", where: "p.41-60", count: 4 }
];
{
  const f = 作る(三);
  見る("手がかり無しなら 全部（構成案の 下見）", 題名(f()), ["第1問 古代", "第2問 中世", "第3問 近世"]);
  見る("題で 1 つに 絞る", 題名(f({ title: "第2問 中世", number: 2 })), ["第2問 中世"]);
  見る("題の 前後の 空白は 見ない", 題名(f({ title: "  第3問 近世 ", number: 3 })), ["第3問 近世"]);
  見る("知らない 題なら 番号へ 落ちず 全部（作り話を 出さない）",
       題名(f({ title: "第9問 存在しない", number: 9 })), ["第1問 古代", "第2問 中世", "第3問 近世"]);
  見る("題が 空なら 番号で 引く", 題名(f({ title: "", number: 1 })), ["第1問 古代"]);
  見る("範囲の 外の 番号なら 全部", 題名(f({ title: "", number: 99 })), ["第1問 古代", "第2問 中世", "第3問 近世"]);
}

/* ★ いちばん 大事な ところ。plan は 問題 0 の 大問を 落としてから 番号を
   振り直すので、番号だけで 引くと **1 つ ずれる**。 */
{
  const ずれ = [
    { title: "第1問 古代", where: "p.10-20", count: 4 },
    { title: "", where: "", count: 0 },                    /* 落ちる（中身なし） */
    { title: "第3問 近世", where: "p.41-60", count: 4 }
  ];
  const f = 作る(ずれ);
  見る("落ちる 大問が 途中に あっても、題なら 正しく 当てる",
       題名(f({ title: "第3問 近世", number: 2 })), ["第3問 近世"]);
  /* 題が 空でも 「大問 N」という 仮の 名が 入る ので、送る 数は 減らない。
     減らないからこそ、**plan 側だけが 落とす**（問題 0 の 大問）ことで
     番号が ずれる。ここが 題で 引く 理由。 */
  見る("題が 空でも 仮の 名が 付く（黙って 落とさない）",
       題名(f()), ["第1問 古代", "大問 2", "第3問 近世"]);
  /* ★ ずれの 実演。plan は 問題 0 の 「大問 2」を 落として 振り直すので、
     「第3問 近世」は plan では **2 番**に なる。
     番号で 引くと 「大問 2」を 指して しまう（＝別の 大問の 問題を 作る）。 */
  見る("番号だけで 引くと ずれる（題を 空に して 実演）",
       題名(f({ title: "", number: 2 })), ["大問 2"]);
  見る("同じ 場面でも 題が あれば 正しい 方を 指す",
       題名(f({ title: "第3問 近世", number: 2 })), ["第3問 近世"]);
}

/* 同じ 題が 2 つ ある ときは、どちらか 分からないので 絞らない。 */
{
  const 重 = [
    { title: "第1問", where: "p.1-10", count: 4 },
    { title: "第1問", where: "p.11-20", count: 4 }
  ];
  const f = 作る(重);
  見る("同じ 題が 2 つ なら 絞らない（取り違えない）",
       題名(f({ title: "第1問", number: 1 })), ["第1問", "第1問"]);
}

/* 中身が 何も 無ければ 送らない（サーバが 自分で 決める）。 */
{
  const 空 = [{ title: "大問 1", where: "", count: 0 }];
  const f = 作る(空);
  見る("どこから 出すかが 決まって いなければ 送らない", f({ title: "大問 1", number: 1 }), undefined);
  見る("範囲が 空なら 送らない", 作る([])({ title: "x", number: 1 }), undefined);
}

console.log("\n══ まとめ ══\n  合格 " + 合 + " / 不合格 " + 否 + "\n");
process.exit(否 ? 1 : 0);
