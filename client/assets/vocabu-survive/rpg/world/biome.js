/** 高さ・湿り・暖かさ から 風土を 決める。 */
/* h は 大陸の うねり（0〜1）。0.42 あたりが 岸。
   ★ 境目は **実測した 散らばりから 決めた**（2026-09-02）。
     見当で 置くと、草原 0.1%・浜 41% の ような 偏りに なる。
       山 中央値 0.33 / 7割 0.51 / 9割 0.79
       湿 中央値 0.50 / 暖 中央値 0.50（南北で 決まる ので 端まで 広い）
     ねらい: 草原 と 森 を 主役に、雪・砂・沼・火山は「行く 場所」に。 */
export function pickBiome(h, wet, warm, mountain) {
  if (h < 0.435) return "shore";                      /* 岸ぎわ・海の底 */
  if (mountain > 0.80 && warm > 0.72) return "volcano";
  if (mountain > 0.74) return "highland";
  if (warm < 0.17) return "snow";
  if (warm > 0.84 && wet < 0.44) return "desert";
  if (wet > 0.78) return "swamp";
  if (mountain > 0.58) return "highland";
  if (wet > 0.56) return "forest";
  return "meadow";
}
