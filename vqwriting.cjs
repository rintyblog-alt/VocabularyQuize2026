#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════
   vqwriting.cjs — Lumi の 文章が **AI らしく ならない** か（2026-08-31・訴え）。

   訴え:「AI らしい 文章を 作るのは やめて ほしい。
         ちゃんと 抽象すぎず、具体的に 書いて ほしい。Live が。」

   ★ 「具体的に 書いて」と 1 行 足すだけでは 効かない（今日 何度も 見た）。
     **何を 書いては いけないかを 名指しする。**
     AI の 文章が 薄く なるのは 決まった 言い回しが 出る からで、
     それは **数えられる**。

   使い方: node vqwriting.cjs
   ══════════════════════════════════════════════════════════════════════════ */
"use strict";
const fs = require("fs");
const path = require("path");
let 済 = 0, 落 = 0; const 落ち = [];
const 節 = (t) => console.log("\n══ " + t + " ══");
const 見 = (ok, 名, 追) => {
  if (ok) { 済++; console.log("  ok   " + 名 + (追 !== undefined ? "  → " + JSON.stringify(追).slice(0, 200) : "")); }
  else { 落++; 落ち.push(名); console.log("  NG   " + 名 + (追 !== undefined ? "  → " + JSON.stringify(追).slice(0, 320) : "")); }
};
const SRC = fs.readFileSync(path.join(__dirname, "server/src/worker.js"), "utf8");

節("① 使わせない 言い回しが 名指しで 並ぶ");
const 禁 = ["さまざまな", "多様な", "幅広い", "さらなる", "が 求められます",
  "と 言えるでしょう", "学びを 深めたい", "貴社／貴学"];
禁.forEach((w) => 見(SRC.indexOf(w) >= 0, "「" + w + "」を 名指しで 禁じて いる"));
見(/AI が 書いた ような 文章に しないでください/.test(SRC), "★ **AI らしい 文章を 書かない**と 言えて いる");
見(/三段構え/.test(SRC), "「まず・次に・最後に」の 三段構えを 禁じる");
見(/頑張って いきたいと 思います/.test(SRC), "決まり文句の 結びを 禁じる");

節("② 代わりに 何を 書くかを 決めて いる");
見(/1 文に 1 つ 入れます/.test(SRC), "★ **1 文に 1 つ**という 数の 決まりが ある");
見(/\*\*数\*\*（何回・何人・何時間・何点・何年）/.test(SRC), "★ 数を 入れさせる");
見(/固有名詞/.test(SRC) && /その 場の 出来事/.test(SRC), "固有名詞・出来事を 入れさせる");
見(/（悪い）/.test(SRC) && /（よい）/.test(SRC), "★ 悪い例と よい例を **並べて** 見せる");
見(/コミュニケーション能力が 高まった/.test(SRC), "★ 抽象語の 言い換え方を 例で 示す");
見(/初対面の 相手に 自分から 話しかけて/.test(SRC), "よい例が 具体（動作）で 書かれて いる");

節("③ 人の 文章を 壊さない");
見(/その 人の 言い回しを 残します/.test(SRC), "★ 直す ときは **本人の 言い回しを 残す**");
見(/その 人の 文章では なく なります/.test(SRC), "なぜ 残すのかが 書いて ある");
見(/事実を 足さない/.test(SRC), "★ **書いて いない 出来事・数字を 作らない**");
見(/何を 書き足せば よいかを 質問/.test(SRC), "★ 足りない ときは **聞く**（でっち上げない）");

節("④ Lumi の 頼み文に 入って いる");
見(/lines\.push\("【文章の 書きかた/.test(SRC), "★ Live の 人がらの 中に 入って いる");
{
  const i = SRC.indexOf('lines.push("【話し方】")');
  const j = SRC.indexOf('lines.push("【文章の 書きかた');
  見(i >= 0 && j > i, "話し方の すぐ あと（埋もれない 位置）", { 話し方: i, 書きかた: j });
}

節("⑤ 文字化けが 混ざって いない");
{
  const 露 = SRC.match(/[Ѐ-ӿ]+/g) || [];
  見(露.length === 0, "★ キリル文字が 1 つも ない（前に 混ざった ことが ある）", 露.slice(0, 4));
  /* ★ ハングルは **わざと 入って いる ところが ある**
     （教材名から 1 文字 混ざる のを 落とす ための 正規表現と、その 説明）。
     だから **Lumi の 頼み文の 中だけ**を 見る。 */
  const 頭 = SRC.indexOf("async function liveSystemInstruction");
  const 尾 = SRC.indexOf("\n}", SRC.indexOf('lines.push("【できること】")'));
  const 頼 = SRC.slice(頭, 尾 > 頭 ? 尾 : 頭 + 40000);
  const 韓 = 頼.match(/[가-힣]+/g) || [];
  見(韓.length === 0, "★ Lumi の 頼み文に ハングルが 混ざって いない", 韓.slice(0, 4));
  const 露2 = 頼.match(/[Ѐ-ӿ]+/g) || [];
  見(露2.length === 0, "★ Lumi の 頼み文に キリル文字が 混ざって いない", 露2.slice(0, 4));
}

console.log("\n────────────────────────────────");
console.log("  ok " + 済 + " / NG " + 落);
if (落) console.log("  落ちた: " + 落ち.join(" / "));
process.exit(落 ? 1 : 0);
