/* ══════════════════════════════════════════════════════════════════════
   数式の 中に 混じった HTML の 札を、意味を 保った まま TeX へ 直せるか。

   訴え（2026-09-06・Rinty さん）:
     「数学記号が 描画されずに タグが 剥き出しに なってます」
     紙に  y = ax < sup > 2 < /sup > +bx + c  と 出ていた。

   ★ いちばん 大事なのは「**消さない**」こと。
     <sup>2</sup> を ただ 外すと ax+bx+c に なり、**別の 式**に なる。
   ★ `a < b` の 「<」は 正しい 数式。触っては いけない。
   ══════════════════════════════════════════════════════════════════════ */
const fs = require("fs");
const src = fs.readFileSync(__dirname + "/client/core/math/parse.js", "utf8");
new Function(src)();                      /* IIFE が globalThis へ VQM を置く */
const P = globalThis.VQM && globalThis.VQM.parse;
if (!P || !P.抜く) { console.error("✗ VQM.parse が 取れません"); process.exit(1); }

/* $…$ を 抜いて、組む 側へ 渡る latex を 取り出す。 */
function 式(text) {
  const 表 = {};
  P.抜く(text, 表);
  return Object.keys(表).map((k) => 表[k].latex);
}
/* 数式を 抜いた あとの **本文**（ここは 触っては いけない）。 */
function 本文(text) { return P.抜く(text, {}); }
let 合 = 0, 否 = 0;
function 見る(名, 実, 期) {
  const a = JSON.stringify(実), b = JSON.stringify(期);
  if (a === b) { console.log("  ✓ " + 名); 合++; }
  else { console.log("  ✗ " + 名 + "\n      出た: " + a + "\n      ほしい: " + b); 否++; }
}

console.log("\n══ 式の中の HTML の札 ══\n");

見る("訴えの 式（2 乗が 札で 書かれている）",
     式("二次関数 $y = ax<sup>2</sup>+bx+c$ のグラフ"), ["y = ax^{2}+bx+c"]);
見る("下つき（添字）", 式("$a<sub>n</sub> = 2n$"), ["a_{n} = 2n"]);
見る("2 つ 以上 混じる", 式("$x<sup>2</sup>+y<sup>2</sup>=r<sup>2</sup>$"),
     ["x^{2}+y^{2}=r^{2}"]);
見る("札の 中が 2 文字 以上", 式("$10<sup>-3</sup>$"), ["10^{-3}"]);
見る("大文字の 札", 式("$x<SUP>2</SUP>$"), ["x^{2}"]);
見る("逃がした 形（&lt;sup&gt;）でも 直す",
     式("$ax&lt;sup&gt;2&lt;/sup&gt;+b$"), ["ax^{2}+b"]);

console.log("");
見る("★ 「<」は 数式として 正しい。触らない", 式("$a < b$"), ["a < b"]);
見る("★ 「<=」も 触らない", 式("$x <= 3$"), ["x <= 3"]);
見る("★ もともと TeX で 書かれた 式は そのまま", 式("$y = ax^2 + bx + c$"), ["y = ax^2 + bx + c"]);
見る("★ \\sup（TeX の 命令）を 壊さない", 式("$\\sup_{n} a_n$"), ["\\sup_{n} a_n"]);

console.log("");
見る("飾りの 札は 外す（意味を 持たない）", 式("$<b>x</b> = 1$"), ["x = 1"]);
見る("改行の 札は 空白へ", 式("$a<br>b$"), ["a b"]);
見る("display（$$）でも 効く", 式("$$E = mc<sup>2</sup>$$"), ["E = mc^{2}"]);
見る("札だけの 式は 空に なる（記号ごと 消える）", 式("$<br>$"), []);

/* 本文の 側は 変えない（数式の 外の <sup> は これまでどおり 本文の 札）。 */
見る("★ 数式の 外の 札には 触らない",
     本文("重さは 3<sup>2</sup> kg です"), "重さは 3<sup>2</sup> kg です");

/* ══ ② その場で 組む 道（vq2-app の 数式に組む / katexOf）══════════
   ここは 「抜く」を 通らない。**同じ 直しが 外から 呼べる**ことを 確かめる。
   これを 忘れると、紙は 直ったのに 画面は 剥き出しの まま に なる。 */
console.log("");
const 直 = P.札をTeXへ;
見る("★ 外から 呼べる（公開されている）", typeof 直, "function");
見る("その場で 組む 道でも 直る", 直("ax<sup>2</sup>+bx+c"), "ax^{2}+bx+c");
見る("esc を 戻した あとの 形でも 直る", 直("ax&lt;sup&gt;2&lt;/sup&gt;"), "ax^{2}");
見る("触る ものが 無ければ そのまま 返す", 直("x^2 + 1"), "x^2 + 1");
見る("空でも 落ちない", 直(""), "");
見る("null でも 落ちない", 直(null), "");

console.log("\n══ まとめ ══\n  合格 " + 合 + " / 不合格 " + 否 + "\n");
process.exit(否 ? 1 : 0);
