/* ══════════════════════════════════════════════════════════════════════════
   vqlivewatch.cjs — 「聞いています」の まま 止まる のを 拾う
   **返しっぱなしの 見張り**が、ちゃんと 組まれているかを 見る。

   訴え（2026-08-28）:
     「クエスチョンに 限らず、聞いていますの まま 止まって、
       こちらから 一言 言わないと 動かない」

   ★ ここは **作りの 検査**（source check）であって、
     実際に Lumi が 黙ったときの 動きを 見たものでは ない。
     声の やりとりは 本物の 鍵と 音が 要るので、ここでは 測れない。
     測れないことを 測ったふりに しないため、そう 書いておく。

   見るところ（js-src/vq-live の 中身）:
     ① 道具の 答えを 返した **すぐあと**に 見張りを 仕込んでいる
     ② 次の 道具が 動いたら やめる／人が しゃべったら やめる
     ③ 段取り（askPlan）の あとは「喋ったから もういい」と しない
     ④ 2 回で あきらめる（延々と 送らない）
     ⑤ 窓が 出ている あいだ・声が 出ている あいだは 待つ（送らない）
     ⑥ 窓を 閉じたら 時計を 必ず 止める

   実行: node vqlivewatch.cjs
   ══════════════════════════════════════════════════════════════════════════ */
"use strict";
const fs = require("fs");
const S = fs.readFileSync(__dirname + "/js-src/vq-live.9628a32d29.js", "utf8");
let ok = 0, ng = 0;
const T = (name, cond, extra) => {
  if (cond) { ok++; console.log("✅ " + name); }
  else { ng++; console.log("❌ " + name + (extra !== undefined ? " → " + String(extra).slice(0, 200) : "")); }
};

/* ① 返したあと すぐ 仕込む */
const 返す = S.indexOf('toolResponse: { functionResponses: resps }');
const 仕込 = S.indexOf("返事の見張りを仕込む(resps)", 返す);
T("① 道具の 答えを 返した すぐあとに 見張りを 仕込む",
  返す > 0 && 仕込 > 返す && 仕込 - 返す < 700, { 返す, 仕込 });

/* 見張りの 本体を 切り出す */
const i = S.indexOf("function 返事を待つ()");
const 本 = i > 0 ? S.slice(i, S.indexOf("\n  }", i) + 4) : "";
T("見張りの 本体が ある", 本.length > 400, 本.length);

T("② 次の 道具が 動いたら やめる", /道具回[^\n]*!==[^\n]*見張り基[\s\S]{0,40}return/.test(本));
T("② 人が しゃべったら やめる", /人の番[^\n]*!==[^\n]*見張り人[\s\S]{0,40}return/.test(本));
T("③ 段取りの あとは 喋っても やめない",
  /!st\.見張り段 &&[\s\S]{0,60}turnAt[\s\S]{0,40}見張り番/.test(本), 本.match(/.*見張り番.*/g));
T("④ 2 回で あきらめる", /見張り回 > 2[\s\S]{0,20}return/.test(本));
T("⑤ 窓・声・組み立て中は **やめずに 待つ**（もう一度 時計を 置く）",
  /問い窓 \|\| st\.speaking \|\| st\.inTurn[\s\S]{0,180}setTimeout\(返事を待つ/.test(本));
T("⑤ 送るのは **人に 聞こえない 合図**（自動で送る）", /自動で送る\(文\)/.test(本));
T("⑥ 段取りの あとは startPlan を 名指しで 促す", /すぐ startPlan を呼んでください/.test(本));

/* 窓を 閉じたら 時計を 止める */
const j = S.indexOf("function 問い窓を閉じる()");
const 閉 = j > 0 ? S.slice(j, j + 900) : "";
T("⑥ 窓を 閉じたら 見張りと 切り上げの 時計を 止める",
  /clearInterval\(問い窓\.見張り\)/.test(閉) && /clearTimeout\(問い窓\.切上\)/.test(閉), 閉.length);

/* 促し（長い仕事の 続き）とは 別ものである こと */
T("促し（続きを促す）とは 別の 時計（混ぜていない）",
  /st\.見張りt/.test(本) && !/st\.促しt/.test(本));

console.log("\n★ これは **作りの 検査**です。実際に Lumi が 黙ったときの 動きは"
  + "\n  本物の 声の やりとりが 要るので、ここでは 測っていません。");
console.log("\n" + ok + " 件 通過 ／ " + ng + " 件 失敗");
process.exit(ng ? 1 : 0);
