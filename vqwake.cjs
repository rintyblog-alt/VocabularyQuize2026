/* ══════════════════════════════════════════════════════════════════════
   「ルミ」と呼ばれたかの判定を、**実機が返した字**で試す。

   ★ 期待値は 私の想像ではなく、iPhone（iOS 18.7 / Safari 26.6）で
     実際に「ルミ」と 3 回言ったときの記録から取っている。
     診断ページ /live-check.html の出力そのもの。

   ★ 当てにいくだけでは駄目で、**普通の会話で誤って始まらない**ことも
     同時に見る。片方だけ通しても意味がない。
   ══════════════════════════════════════════════════════════════════════ */
const path = require("path");
const W = require(path.join(__dirname, "client", "vq-wake.js"));

let pass = 0, fail = 0;
function hit(t, note) {
  const r = W.why(t);
  if (r.hit) { pass++; console.log("  ✓ 「" + t + "」→ 起きる（" + r.reason + "）"); }
  else { fail++; console.log("  ✗ 「" + t + "」→ **起きない** " + (note || "") + " / " + r.reason); }
}
function miss(t, note) {
  const r = W.why(t);
  if (!r.hit) { pass++; console.log("  ✓ 「" + t + "」→ 起きない（正しい）"); }
  else { fail++; console.log("  ✗ 「" + t + "」→ **誤って起きる** " + (note || "") + " / " + r.reason); }
}
function sec(t) { console.log("\n■ " + t); }

/* ── ① 実機が「ルミ」と言ったときに返した字（全部）─────────────
   出典: 2026-08-15 の診断記録。1 つでも落ちたら、その分だけ
   「呼んでも反応しない」が起きる。 */
sec("実機が返した字（iOS 18.7 / Safari 26.6）");
/* 言い終わった形（これは必ず当てる） */
["ルビー", "海", "海海", "海海海", "るみ",
 "エルミ", "エル海", "恵海", "エミ", "恵み",
 "テルミ", "ヘルミ", "テイルミ", "オイル", "エル", "ヘイ"]
  .forEach((t) => hit(t, "← 実機がこう返した"));

/* ★ **言いかけの断片**（「ル」「ヘル」）は 1 文字ぶんしかなく、
   これで起こすと 普通の言葉で誤って始まる。
   断片そのものは採らない。**その 0.2〜2 秒後に届く続き**で起きればよい。
   だから「1 回の発話につき、届いた字のどれかが当たる」で見る。 */
sec("1 回の呼びかけごとに、どれかが当たるか（実機の記録どおりの順）");
const 発話 = [
  ["ル", "ルビー", "ルビー"],                       /* 1 回目 */
  ["海", "海海", "海海海", "海", "るみ", "海海"],   /* 2 回目 */
  ["るみ", "るみ", "るみ"],                         /* 3 回目 */
  ["恵", "エル", "エルミ", "エルミ", "エル海", "恵海", "エミ", "恵み"],
  ["手", "ヘイ", "ヘル", "テルミ", "テルミ", "ヘルミ", "テイルミ"]
];
発話.forEach((g, i) => {
  const 当たった = g.filter((t) => W.why(t).hit);
  if (当たった.length) {
    pass++; console.log("  ✓ " + (i + 1) + " 回目 → 起きる（" + 当たった.length + "/" + g.length + " 個が当たった）");
  } else {
    fail++; console.log("  ✗ " + (i + 1) + " 回目 → **一度も起きない** " + JSON.stringify(g));
  }
});

/* ── ② 素直な言い方 ─────────────────────────────────────────── */
sec("素直な言い方");
["ルミ", "るみ", "ルーミ", "Lumi", "lumi", "ヘイルミ", "ヘイ、ルミ",
 "ルミー", "留美", "瑠美", "ルミ！", "る・み"].forEach((t) => hit(t));

/* ── ③ **誤って始まってはいけない**もの ──────────────────────
   ここを緩めると「勝手に話しかけてくる」になる。落とさない。 */
sec("誤って始まってはいけない");
[
  "どんなお手伝いをしましょうか",
  "今日の海はきれいだった",
  "海の生き物についての問題を作りたい",
  "恵みの雨が降っている",
  "次の問題に進んでください",
  "英語のテスト勉強をしないといけない",
  "ちょっと待ってて、いま準備するから",
  "この単語の意味がわからない",
  "くるみパンを買ってきた",
  "組み合わせを考える問題です"
].forEach((t) => miss(t, "← 普通の会話"));

/* ── ④ 境目 ─────────────────────────────────────────────────── */
sec("境目");
miss("", "空");
miss("あいうえおかきくけこさしすせそたちつてとなにぬねの", "長すぎる");
hit("ヘイ ルミ", "空白ありでも当てる");
hit("ﾙﾐ".normalize("NFKC"), "半角カナ");

/* ── ⑤ アプリ側と食い違っていないか ─────────────────────────
   ★ 判定は **1 か所**にしかない、を確かめる。2 か所にあると
     片方だけ直して「直したのに直らない」になる。 */
sec("判定が 1 か所にまとまっているか");
const fs = require("fs");
const IDX = require("./vqsrc.cjs").丸ごと();
const CHK = fs.readFileSync(path.join(__dirname, "client", "live-check.html"), "utf8");
function ok(name, cond) {
  if (cond) { pass++; console.log("  ✓ " + name); }
  else { fail++; console.log("  ✗ " + name); }
}
ok("アプリが 共通の判定を読んでいる", /vq-wake\.js/.test(IDX));
ok("診断ページも 同じものを読んでいる", /vq-wake\.js/.test(CHK));
/* ★ この検査の ねらいは 「**当て字の並びが 2 か所に ならないこと**」。
   書いた 当時は 並びが index.html の 中にも 直に あったので
   「1 つも 無いこと」で 見ていた。
   いまは client/vq-wake.js が bundle-core に 束ねられていて、
   丸ごと() が **その 1 つを 含む**（2026-08-28）。
   ねらいどおり **ちょうど 1 か所**で 見る。 */
ok("当て字の並びが 2 か所に なっていない（ちょうど 1 か所）",
  (IDX.match(/"るーみ", "るうみ", "ろみ", "るび",/g) || []).length === 1);

console.log("\n" + (fail ? "❌ 落ちています" : "✅ 全部通りました")
  + "  通過 " + pass + " / 失敗 " + fail);
process.exit(fail ? 1 : 0);
